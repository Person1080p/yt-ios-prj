//! Listening reports from clients -> Last.fm now playing / scrobbles, YouTube history, local history.

use std::{sync::Arc, time::Duration};

use rusqlite::params;
use serde::Deserialize;

use crate::{
    models::{now, Track},
    state::{AppState, ServerEvent, SharedState},
};

/// Last.fm's rule: tracks > 30s, scrobbled after half the track or 4 minutes, whichever comes first.
const MIN_TRACK_SECS: f64 = 30.0;
const MAX_THRESHOLD_SECS: f64 = 240.0;

#[derive(Debug, Clone)]
pub struct PlaySession {
    pub track: Track,
    pub source: String,
    pub started_at: i64,
    pub last_pos: f64,
    pub listened: f64,
    pub recorded: bool,
}

#[derive(Debug, Deserialize)]
#[serde(rename_all = "camelCase")]
pub struct PlaybackEvent {
    /// Random id generated by the client for each play of a track.
    pub session_id: String,
    pub track: Track,
    /// start | progress | end
    pub event: String,
    pub position: f64,
    #[serde(default)]
    pub duration: Option<f64>,
    #[serde(default)]
    pub source: Option<String>,
}

pub async fn handle(state: &SharedState, ev: PlaybackEvent) -> anyhow::Result<()> {
    let mut sessions = state.sessions.lock().await;
    let ts = now();
    sessions.retain(|_, s| ts - s.started_at < 60 * 60 * 6);

    let is_new = !sessions.contains_key(&ev.session_id);
    let s = sessions.entry(ev.session_id.clone()).or_insert_with(|| PlaySession {
        track: ev.track.clone(),
        source: ev.source.clone().unwrap_or_else(|| "youtube".into()),
        started_at: ts,
        last_pos: ev.position,
        listened: 0.0,
        recorded: false,
    });
    if let Some(src) = &ev.source {
        s.source = src.clone();
    }

    if is_new || ev.event == "start" {
        let st = state.clone();
        let track = ev.track.clone();
        tokio::spawn(async move {
            let main = st.db.active_profile().await == crate::services::profile::MAIN;
            if main && st.lastfm.session().await.is_some() && st.db.get_bool("prefs.scrobble", true).await {
                if let Err(e) = st.lastfm.now_playing(&track).await {
                    tracing::warn!("last.fm now playing: {e:#}");
                }
            }
        });
    }

    // Count only forward progress in small steps, so seeking doesn't count as listening.
    let delta = ev.position - s.last_pos;
    if delta > 0.0 && delta < 20.0 {
        s.listened += delta;
    }
    s.last_pos = ev.position;

    let duration = ev.duration.filter(|d| d.is_finite() && *d > 0.0).or(s.track.duration.map(|d| d as f64));
    let threshold = duration
        .filter(|d| *d >= MIN_TRACK_SECS)
        .map(|d| (d / 2.0).min(MAX_THRESHOLD_SECS));

    if !s.recorded {
        if let Some(th) = threshold {
            if s.listened >= th {
                s.recorded = true;
                let st = state.clone();
                let session = s.clone();
                crate::services::ytlog::spawn("record play", async move { record_play(st, session).await });
            }
        }
    }
    if ev.event == "end" {
        sessions.remove(&ev.session_id);
    }
    Ok(())
}

async fn record_play(state: SharedState, s: PlaySession) {
    let vid = s.track.video_id.clone();
    let _ = state.db.upsert_tracks(vec![s.track.clone()]).await;

    let profile = state.db.active_profile().await;
    let fresh = profile == crate::services::profile::FRESH;
    // The fresh profile never touches your Last.fm or YouTube history; its plays only feed its own
    // local history (which drives its recommendations). YouTube doesn't accept play reports from
    // anonymous visitors.
    let want_scrobble =
        !fresh && state.lastfm.session().await.is_some() && state.db.get_bool("prefs.scrobble", true).await;
    let want_yt = !fresh && state.yt.signed_in_now().await && state.db.get_bool("prefs.report_youtube", true).await;

    let (src, started) = (s.source.clone(), s.started_at);
    let v = vid.clone();
    let id: i64 = match state
        .db
        .call(move |c| {
            c.execute(
                "INSERT INTO history(video_id, played_at, source, scrobbled, yt_reported, profile) VALUES(?1,?2,?3,?4,?5,?6)",
                params![v, started, src, if want_scrobble { 0 } else { 2 }, if want_yt { 0 } else { 2 }, profile],
            )?;
            Ok(c.last_insert_rowid())
        })
        .await
    {
        Ok(id) => id,
        Err(e) => {
            tracing::error!("recording history: {e:#}");
            return;
        }
    };

    if want_scrobble {
        match state.lastfm.scrobble(&s.track, s.started_at).await {
            Ok(()) => {
                let _ = state.db.call(move |c| c.execute("UPDATE history SET scrobbled=1 WHERE id=?1", [id])).await;
                tracing::info!("scrobbled {} - {}", s.track.artist, s.track.title);
            }
            Err(e) => tracing::warn!("scrobble failed (will retry): {e:#}"),
        }
    }
    if want_yt {
        match state.yt.add_history(&vid).await {
            Ok(()) => {
                let _ = state.db.call(move |c| c.execute("UPDATE history SET yt_reported=1 WHERE id=?1", [id])).await;
            }
            Err(e) => tracing::warn!("youtube history report failed: {e:#}"),
        }
    }
    state.emit(ServerEvent::Scrobbled { video_id: vid });
}

/// Re-send YouTube history reports that failed in the last day (a few per round, oldest first).
/// Older plays are left alone: YouTube files a report under the time it arrives, so a days-old
/// play would show up in your history as if you'd just played it.
async fn retry_youtube(state: &Arc<AppState>) -> anyhow::Result<()> {
    if !state.yt.signed_in_now().await || !state.db.get_bool("prefs.report_youtube", true).await {
        return Ok(());
    }
    let profile = state.db.active_profile().await;
    if profile == crate::services::profile::FRESH {
        return Ok(());
    }
    let cutoff = now() - 60 * 60 * 24;
    let pending: Vec<(i64, String)> = state
        .db
        .call(move |c| {
            let mut stmt = c.prepare(
                "SELECT id, video_id FROM history WHERE yt_reported=0 AND played_at>?1 AND profile=?2 ORDER BY played_at LIMIT 10",
            )?;
            let rows = stmt.query_map(params![cutoff, profile], |r| Ok((r.get(0)?, r.get(1)?)))?;
            rows.collect()
        })
        .await?;
    for (id, vid) in pending {
        state.yt.add_history(&vid).await?;
        state.db.call(move |c| c.execute("UPDATE history SET yt_reported=1 WHERE id=?1", [id])).await?;
    }
    Ok(())
}

/// Periodically retry scrobbles that failed (e.g. Last.fm down or server offline).
pub fn spawn_retry_loop(state: SharedState) {
    tokio::spawn(crate::services::ytlog::with_origin("play report retry loop", async move {
        let mut tick = tokio::time::interval(Duration::from_secs(600));
        loop {
            tick.tick().await;
            if let Err(e) = retry_once(&state).await {
                tracing::debug!("scrobble retry: {e:#}");
            }
        }
    }));
}

async fn retry_once(state: &Arc<AppState>) -> anyhow::Result<()> {
    if let Err(e) = retry_youtube(state).await {
        tracing::debug!("youtube history retry: {e:#}");
    }
    if state.lastfm.session().await.is_none() {
        return Ok(());
    }
    // Last.fm rejects scrobbles older than 14 days.
    let cutoff = now() - 60 * 60 * 24 * 13;
    let pending: Vec<(i64, String, i64)> = state
        .db
        .call(move |c| {
            let mut stmt = c.prepare(
                "SELECT id, video_id, played_at FROM history WHERE scrobbled=0 AND played_at>?1 ORDER BY played_at LIMIT 50",
            )?;
            let rows = stmt.query_map([cutoff], |r| Ok((r.get(0)?, r.get(1)?, r.get(2)?)))?;
            rows.collect()
        })
        .await?;
    for (id, vid, at) in pending {
        let Some(track) = state.db.get_track(&vid).await? else { continue };
        if state.lastfm.scrobble(&track, at).await.is_ok() {
            state.db.call(move |c| c.execute("UPDATE history SET scrobbled=1 WHERE id=?1", [id])).await?;
        } else {
            break;
        }
    }
    Ok(())
}
